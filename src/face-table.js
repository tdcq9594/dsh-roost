/** face id → 名字（由 FACE_IDS 反推，避免两份表互相漂移） */
export const FACE_NAMES = Object.freeze(
  Object.fromEntries(Object.entries(FACE_IDS).map(([name, id]) => [id, name])),
);

/** 出站要用的控制字符前缀：QQ 私有区的 0x14 */
export const FACE_PREFIX = 0x14;

/**
 * 最常用的那一批小黄脸。
 *
 * **刻意不给全表**：108 个名字塞进系统提示词，光这一段就三四百字，
 * 而且大部分名字（`右哼哼`、`凋谢`、`勾引`）她一年也用不上一次。
 * 二十来个覆盖日常语气就够了——模型真要别的，入站见过名字自然会学。
 *
 * 顺序按「聊天气里出场率」排，不是码表顺序：微笑/呲牙/偷笑 是最高频的三个。
 */
export const POPULAR_FACES = Object.freeze([
  '微笑', '呲牙', '偷笑', '流泪', '得意', '害羞',
  '白眼', '捂脸', '发怒', '惊恐', '难过', '疑问',
  '睡', '憨笑', '坏笑', '赞', '握手', '胜利',
  '抱拳', '玫瑰', '爱心', '蛋糕', '太阳', 'OK',
]);

/**
 * 给小黄脸的提示词片段。
 *
 * ## 为什么必须有这一段
 *
 * `channel.js` 的 `encodeFaceTags()` 早就能把 `【表情: 微笑】` 编码成真的 QQ
 * 表情，而且挂在四条出站路的唯一汇合点上——但**提示词从来没告诉模型有这回事**。
 * 结果就是这个功能一直是空转的：模型不写标记，编码器一次也跑不到。
 *
 * 入站那边会把收到的表情渲染成 `【表情: 名字】`，模型理论上能自己学会模仿，
 * 但那是「运气好见过一次」，不能当设计。
 *
 * ## 为什么不说「每条都配一个」
 *
 * 小黄脸是语气不是标点。每句话尾巴挂一个，读起来就像十年前的表情包刷屏。
 * 这里明说「偶尔、最多一两个」，比事后再加一道概率门禁好——门禁会跟模型
 * 想表达的情绪打架，表现成「明明情绪到了却不许用」，更假。
 *
 * @param {{ max?: number }} [o]
 * @returns {string}
 */
export function faceHint({ max = 24 } = {}) {
  /** 只保留码表里真有的：`FACE_IDS` 改了以后这里不会漏出一个发不出去的名字 */
  const names = POPULAR_FACES.filter((n) => Object.hasOwn(FACE_IDS, n)).slice(0, max);
  if (!names.length) return '';
  return [
    '【QQ 小黄脸】你可以在正文里写 `【表情: 微笑】` 这种标记，发出去会变成真的 QQ 表情。',
    `可用：${names.join('、')}。`,
    '一条回复最多带一两个，只在情绪真到那儿的时候用；每句尾巴都挂一个会很假。',
    '写别的名字会被整段删掉（不会原样发出去），所以只用上面这些。',
  ].join('');
}


/**
 * 入站表情标签 → `【表情: 名字】`。
 *
 * 官方三种形态都要认：
 *   · `<faceType=6,faceId="0",ext="eyJ0ZXh0IjoiIn0=">`（新格式，ext 是 base64 的 `{"text":""}`）
 *   · `<faceType=1,faceId="124">`（老格式，没有 ext）
 *   · 属性顺序变化、`faceType` 是任意数字
 * 所以只按 `faceType=` 圈定标签，再在标签内部捞 `faceId` / `ext`——**不假设顺序**。
 *
 * `ext.text` **优先**于查表：QQ 有些表情 id 会随版本变（同一个 id 前后含义不同），
 * 官方在 ext 里自带文字时就以它为准；没有才退回本地码表。
 *
 * 查不到、ext 也解不出：给 `【表情】`（不带名字）。宁可信息少一点，
 * 也不把 `<faceType=…>` 原样留给模型——它只会照着抄进正文。
 *
 * @param {string} text
 * @returns {string}
 */
export function decodeFaceTags(text) {
  const s = String(text ?? '');
  if (!s || !s.includes('faceType')) return s;
  /**
   * 匹配整段标签、再在内部捞字段，**不要求 `<faceType=` 打头**：
   * 见过 `<faceId="23",faceType=1>` 这种属性倒过来的形态（顺序由 SDK 决定，
   * 不是我们说了算）。先圈定 `<…>`，里面出现 `faceType` 就当表情标签——
   * 正常聊天里不会有人在尖括号里写这三个词。
   */
  return s.replace(/<[^<>]*faceType=[^<>]*>/gi, (tag) => {
    const id = (tag.match(/faceId\s*=\s*"([^"]*)"/i) || [])[1] ?? '';
    const ext = (tag.match(/ext\s*=\s*"([^"]*)"/i) || [])[1] ?? '';
    return faceTextOf(id, ext);
  });
}

/** 单个标签 → `【表情: 名】`；`ext.text` 优先，其次码表，最后无名字 */
function faceTextOf(id, extB64) {
  const fromExt = textInExt(extB64);
  if (fromExt) return `【表情: ${fromExt}】`;
  const key = String(id ?? '').trim();
  const name = key ? FACE_NAMES[Number(key)] : '';
  return name ? `【表情: ${name}】` : '【表情】';
}

/**
 * `ext="eyJ0ZXh0IjoiIn0="` → `text` 字段。
 *
 * 三种失败都当没有：base64 解不出、不是 JSON、`text` 是空串——这几种在真实
 * 账本里都见过（纯图片表情的 ext 就是 `{"text":""}`）。
 */
function textInExt(extB64) {
  const raw = String(extB64 ?? '').trim();
  if (!raw) return '';
  try {
    const json = Buffer.from(raw, 'base64').toString('utf8');
    const obj = JSON.parse(json);
    return String(obj?.text ?? '').trim();
  } catch {
    return '';
  }
}

/**
 * `【表情: 名字】` → QQ 私有协议控制字符（`0x14` + id）。
 *
 * **名字对不上就整段删掉**，不回退成文字：`【表情: 不存在的脸】` 原样发进群，
 * 用户看到的是括号和中文，比不发还怪。所以给 `onMiss` 回调让调用方记日志，
 * 文本本身只负责"干净"。
 *
 * 为什么不用 `\u0014` 字面量：那是个不可见控制字符，写在源码里会被编辑器
 * 悄悄吃掉或换成替换符；用 `String.fromCharCode` 拼出来一眼能看出是什么。
 *
 * @param {string} text
 * @param {(name:string)=>void} [onMiss] 名字没匹配上时的回调（记日志用）
 * @returns {string}
 */
export function encodeFaceTags(text, onMiss) {
  const s = String(text ?? '');
  if (!s || !s.includes('【表情')) return s;
  return s
    .replace(/【表情\s*[:：]\s*([^】]{1,16})】/g, (whole, rawName) => {
      const name = String(rawName ?? '').trim();
      const id = FACE_IDS[name];
      if (id === undefined) {
        onMiss?.(name);
        return '';
      }
      return String.fromCharCode(FACE_PREFIX, id);
    })
    /**
     * 收尾：去掉**残缺**的标记。
     *
     * 调用方是 `channel.js` 的 `send()`，它先按字数截断再调这里。
     * 正文里表情多的时候，截断点可能正好落在 `【表情: 呲` 中间——那条正则
     * 要求有收尾的 `】`，匹配不上，于是半截标记就原样发进群里。
     * 残缺的尾巴只可能是**最后一段**，所以只清行尾/文尾这一处，不动正文中间。
     */
    .replace(/【表情[^】]*$/, '');
}

/**
 * face id → 名字（由 FACE_IDS 反推，避免两份表互相漂移）
 */
export const FACE_NAMES = Object.freeze(
  Object.fromEntries(Object.entries(FACE_IDS).map(([name, id]) => [id, name])),
);

/**
 * 把 `【表情: 名字】` 从正文里删掉。
 *
 * **这是"不发小黄脸"的兜底**：提示词已经不再教这个语法，但模型仍可能
 * 从三处学到——旧会话历史、记忆里存过的正文、群友发表情时入站翻出来的
 * 名字。学到的标记若原样发出去，用户看到的是 `【表情: 微笑】` 这串中文；
 * 若被框架侧编成 `0x14`，又变成"PC 上两个豆腐块"。所以出站一律清掉。
 *
 * 正则和原来编码器用的是同一套（含全角冒号、名字最多 16 字），只是把
 * 替换结果从控制字符改成空串；末尾再清一次残缺标记——`channel.js` 是
 * **先按字数截断再调这里**，截断点可能落在 `【表情: 呲` 中间。
 *
 * @param {string} text
 * @returns {string}
 */
export function stripFaceMarks(text) {
  const s = String(text ?? '');
  if (!s || !s.includes('【表情')) return s;
  return s
    .replace(/【表情\s*[:：]\s*[^】]{1,16}】/g, '')
    .replace(/【表情[^】]*$/, '');
}



/**
 * 入站表情标签 → `【表情: 名字】`。
 *
 * 官方三种形态都要认：
 *   · `<faceType=6,faceId="0",ext="eyJ0ZXh0IjoiIn0=">`（新格式，ext 是 base64 的 `{"text":""}`）
 *   · `<faceType=1,faceId="124">`（老格式，没有 ext）
 *   · 属性顺序变化、`faceType` 是任意数字
 * 所以只按 `faceType=` 圈定标签，再在标签内部捞 `faceId` / `ext`——**不假设顺序**。
 *
 * `ext.text` **优先**于查表：QQ 有些表情 id 会随版本变（同一个 id 前后含义不同），
 * 官方在 ext 里自带文字时就以它为准；没有才退回本地码表。
 *
 * 查不到、ext 也解不出：给 `【表情】`（不带名字）。宁可信息少一点，
 * 也不把 `<faceType=…>` 原样留给模型——它只会照着抄进正文。
 *
 * @param {string} text
 * @returns {string}
 */
export function decodeFaceTags(text) {
  const s = String(text ?? '');
  if (!s || !s.includes('faceType')) return s;
  /**
   * 匹配整段标签、再在内部捞字段，**不要求 `<faceType=` 打头**：
   * 见过 `<faceId="23",faceType=1>` 这种属性倒过来的形态（顺序由 SDK 决定，
   * 不是我们说了算）。先圈定 `<…>`，里面出现 `faceType` 就当表情标签——
   * 正常聊天里不会有人在尖括号里写这三个词。
   */
  return s.replace(/<[^<>]*faceType=[^<>]*>/gi, (tag) => {
    const id = (tag.match(/faceId\s*=\s*"([^"]*)"/i) || [])[1] ?? '';
    const ext = (tag.match(/ext\s*=\s*"([^"]*)"/i) || [])[1] ?? '';
    return faceTextOf(id, ext);
  });
}

/** 单个标签 → `【表情: 名】`；`ext.text` 优先，其次码表，最后无名字 */
function faceTextOf(id, extB64) {
  const fromExt = textInExt(extB64);
  if (fromExt) return `【表情: ${fromExt}】`;
  const key = String(id ?? '').trim();
  const name = key ? FACE_NAMES[Number(key)] : '';
  return name ? `【表情: ${name}】` : '【表情】';
}

/**
 * `ext="eyJ0ZXh0IjoiIn0="` → `text` 字段。
 *
 * 三种失败都当没有：base64 解不出、不是 JSON、`text` 是空串——这几种在真实
 * 账本里都见过（纯图片表情的 ext 就是 `{"text":""}`）。
 */
function textInExt(extB64) {
  const raw = String(extB64 ?? '').trim();
  if (!raw) return '';
  try {
    const json = Buffer.from(raw, 'base64').toString('utf8');
    const obj = JSON.parse(json);
    return String(obj?.text ?? '').trim();
  } catch {
    return '';
  }
}
